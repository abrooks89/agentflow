"""The ``wiki/`` pillar — what the fleet LEARNED, beside ``design/``, ``autodoc/`` and ``status/``.

Layout under a project::

    wiki/
    ├── pages/            # durable pages, Karpathy-wiki style, CREATION-ONLY
    │   ├── done/
    │   └── archived/
    ├── hot.md            # projection: project-wide top-N
    ├── hot-<lane>.md     # projection: per-lane top-N
    └── digest.md         # empty body scaffolded here; CONTENT is the steward's, never this
                          # module's (see `initial_pillar_files`)

TWO KINDS OF FILE, AND ONLY ONE OF THEM IS AUTHORED. A page is written once and never
rewritten by this module; the ``hot*.md`` files are a *projection* — a pure function of the
page set, regenerated wholesale on every refresh. That split is what lets the projection run
without a lock (see the purity banner below) and it is why ``write_page`` refuses to overwrite:
if pages were mutable, the projection would be a cache with an invalidation problem instead of
a rendering with none.

STDLIB ONLY (plus ``pyyaml``, which ``agentflow`` already depends on): no model call, no
network, no clock. ``created`` is DATA carried on the page — a plain ISO string that this module
validates by SHAPE but never parses, compares as a date, or invents. A later epic greps
``agentflow/`` to prove no model call exists here; keep it true.

Callable from a loop skill::

    python -m agentflow.wiki refresh --project <name>
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass
import os
from pathlib import Path
import re
import sys
import tempfile
from typing import Mapping, Sequence

import yaml

from agentflow.atomic_io import atomic_write

#: How many pages a hot projection carries. One number, both levels.
DEFAULT_TOP_N = 20

#: Where durable pages live under a project's ``wiki/``.
PAGES_DIRNAME = "pages"

#: The pillar's own directory name under ``<data_root>/projects/<name>/``. Used only by the CLI.
WIKI_DIRNAME = "wiki"

#: The project-wide projection, and the steward's digest. Both are scaffolded by
#: :func:`initial_pillar_files` and both are markers :func:`missing_pillar_markers` requires.
HOT_FILENAME = "hot.md"
DIGEST_FILENAME = "digest.md"

#: Ceiling on the raw frontmatter block, applied BEFORE ``yaml.safe_load``. YAML aliases share
#: nodes rather than copying them, so ``safe_load`` itself does not blow up — but stringifying an
#: aliased node materialises the expansion, and 340 bytes of nested aliases becomes megabytes at
#: depth 8 and gigabytes at depth 9. Capping the source is the only bound that holds before any of
#: that runs; rejecting non-scalar fields (see :func:`_scalar_text`) closes the same door again.
MAX_FRONTMATTER_CHARS = 4096

#: Ceiling on one frontmatter field. A title is a title.
MAX_FIELD_CHARS = 500

#: Ceiling on a path-forming component (``slug``, ``lane``), in UTF-8 BYTES. One filename may be
#: 255 bytes on ext4 and 255 UTF-16 units on NTFS; a UTF-8 byte count is never below the UTF-16
#: count, so bounding bytes bounds both. The longest name built from a component is the
#: ``atomic_write`` temp for a lane file, ``hot-<lane>.md.<8 random>.tmp``, 20 bytes over the
#: component. 100 also keeps most of Windows' 259-character WHOLE-path limit for the root; the
#: path itself is checked separately (:func:`_check_paths_fit`). :data:`MAX_FIELD_CHARS` alone
#: let a lane through that no filesystem could hold, and refresh died after ``hot.md`` was
#: already rewritten.
MAX_COMPONENT_BYTES = 100

#: What ``atomic_write``'s temp name adds to the file it replaces: ``.<8 random>.tmp``.
_ATOMIC_TEMP_EXTRA = len(".XXXXXXXX.tmp")
#: ``_exclusive_create``'s temp file beside a new page.
_PAGE_TEMP_NAME = ".wiki-XXXXXXXX.tmp"
#: The longest path Windows opens without long-path support: MAX_PATH less its NUL.
_WINDOWS_MAX_PATH = 259

#: Subdirectories of ``pages/`` that hold TERMINAL pages. A page is moved here when it stops
#: being live; it keeps its history but leaves the projection. ``read_pages`` skips them by
#: name at any depth, so a nested live folder still reads while ``pages/done/…`` never does.
TERMINAL_PARTITIONS = frozenset({"done", "archived"})

#: The line every generated projection carries, so a human editing one is told it is futile.
GENERATED_MARKER = (
    "<!-- GENERATED by agentflow.wiki.refresh_projection - do not hand-edit, "
    "the next refresh overwrites this file. -->"
)

_FRONTMATTER_RE = re.compile(r"^---\s*\n(.*?)\n---\s*\n", re.DOTALL)
#: ``created`` must be ``YYYY-MM-DD`` — SHAPE only, never a parse. Ordering is lexicographic, so a
#: value of another shape does not error, it RANKS WRONG: ``"yesterday"`` sorts above every real
#: date and silently takes the top of a hot file. The module already raises on a MISSING
#: ``created``; accepting garbage in it left the loud half guarding the harmless case.
#: ``\Z``, never ``$``: ``$`` also matches just before a trailing newline, so ``"2026-09-01\n"``
#: would pass a ``$``-anchored shape check carrying the newline that SEC-2 is about.
_CREATED_RE = re.compile(r"^\d{4}-\d{2}-\d{2}\Z")

#: Any C0 control or DEL, plus the two Unicode line separators. Rejected in every field that
#: reaches a rendered projection, because ``hot.md`` is a LINE-ORIENTED file and a newline inside
#: a title is a new line in it: the fake entry, the counterfeit GENERATED banner and the planted
#: "SYSTEM:" directive are all just text after a ``\n``. ``yaml.safe_dump`` escapes it on write
#: and ``safe_load`` restores it faithfully, so the page stays well-formed and the injection
#: lands on RENDER — which is why the check has to live on the field, not on the file format.
#: U+2028 and U+2029 ARE IN THE CLASS because Python's ``str.splitlines()`` splits on them: a
#: consumer that reads a hot file line by line — which is every consumer, that being the point of
#: the format — sees a fabricated line from a field the C0 check called clean. They are spelled with
#: ``chr`` rather than as escapes so this file's own bytes stay ASCII and no editor, diff or
#: sanitize grep has to survive an invisible line break in the source.
_LINE_SEPARATORS = chr(0x2028) + chr(0x2029)
_CONTROL_RE = re.compile("[" + r"\x00-\x1f\x7f" + _LINE_SEPARATORS + "]")

#: Names Windows resolves to DEVICES rather than files, at any extension and in any case.
#: ``pages/nul.md`` opens the null device: the write succeeds, the bytes go nowhere, and the
#: page is silently absent from every later read.
_RESERVED_STEMS = frozenset(
    {"con", "prn", "aux", "nul"}
    | {f"com{d}" for d in "123456789"}
    | {f"lpt{d}" for d in "123456789"}
)
#: Characters a Windows filename cannot contain. ``/``, ``\`` and ``:`` are rejected separately
#: (they are the traversal), and these five plus ``"`` are the rest of the set. They matter for a
#: DIFFERENT reason: a lane like ``build|test`` is legal on POSIX and passes every traversal rule,
#: so validation says yes and the OS says no — halfway through a refresh, after ``hot.md`` is
#: already rewritten and before the stale sweep runs.
_WINDOWS_ILLEGAL_CHARS = frozenset('|?*<>"')
#: The exact filename shape a projection refresh writes: ``hot.md`` plus one ``hot-<lane>.md`` per
#: live lane. The stale sweep is scoped to this and nothing else — ``digest.md`` is the steward's
#: file, lives in the same directory, and must survive every refresh.
_HOT_LANE_GLOB = "hot-*.md"
#: A ``[[wikilink]]`` target. Bracket-free inside, so ``[[a]] and [[b]]`` is two links and not one
#: spanning the prose between them — and CONTROL-FREE inside, which is a security property, not
#: tidiness: the projection re-emits every target verbatim, so a target allowed to carry ``\n``
#: is a way to write arbitrary lines into ``hot.md`` from a page body. A ``[[`` with a newline
#: before its ``]]`` is an unclosed bracket, and is now read as one — and the class carries
#: :data:`_LINE_SEPARATORS` for the same reason every other rendered field does.
_WIKILINK_RE = re.compile(r"\[\[([^\[\]\x00-\x1f\x7f" + _LINE_SEPARATORS + r"]+)\]\]")


class WikiFormatError(ValueError):
    """Raised when a page's text is missing or malformed frontmatter.

    Loud on purpose. A half-parsed page (no title, no ``created``) would sort to an arbitrary
    place in the projection and read as a real entry — the failure would be a wrong hot file,
    not an error, and nobody re-reads a hot file to check it.
    """


class PageExistsError(FileExistsError):
    """Raised when ``write_page`` is asked to write a slug that already has a page."""


class NotAPillarError(FileNotFoundError):
    """Raised when a wiki root lacks the provisioned-pillar markers (gh#521).

    A ``FileNotFoundError`` so the CLI's existing exit-2 mapping and ``compose_and_save``'s
    catch-all both already handle it. The remedy is re-provisioning, never creating the markers
    by hand: a hand-made ``digest.md`` is exactly how a mis-aimed root would start passing.
    """


class MissingWikilinkError(ValueError):
    """Raised when ``write_page`` is given a body carrying no ``[[wikilink]]``."""


@dataclass(frozen=True)
class Page:
    """One durable wiki page — a pure value, already parsed.

    ``created`` is the ISO date STRING off the frontmatter, deliberately not a ``date``. Nothing
    here does date arithmetic; ordering is lexicographic, which for ``YYYY-MM-DD`` is the same
    answer without importing a clock and without a parse that can fail on read.

    ``links`` is the ``[[wikilink]]`` target list in first-appearance order, deduplicated. It is
    the future page graph's edge list, which is why the projection re-emits it rather than
    flattening pages to titles.
    """

    slug: str
    title: str
    lane: str | None
    created: str
    body: str
    links: tuple[str, ...] = ()


def extract_links(body: str) -> tuple[str, ...]:
    """The ``[[wikilink]]`` targets in *body*, first-appearance order, deduplicated. PURE.

    A target that is empty once stripped is NOT a target. ``[[   ]]`` matched the pattern, so it
    satisfied :func:`write_page`'s "every page links to something" rule while yielding ``''`` —
    an edge to nothing, rendered into the projection as a literal ``[[]]``. The requirement is a
    link, and the cheapest place to make that true for both the writer and the renderer is here,
    where the target is decided.
    """
    seen: dict[str, None] = {}
    for match in _WIKILINK_RE.finditer(body):
        target = match.group(1).strip()
        if target:
            seen.setdefault(target, None)
    return tuple(seen)


def parse_page(text: str, *, slug: str) -> Page:
    """Parse one page's text into a :class:`Page`. PURE — no file, no clock, no lock.

    Requires a leading ``---`` frontmatter block carrying ``title`` and ``created``; ``lane`` is
    optional (a page can belong to the project rather than to a lane). Anything else raises
    :class:`WikiFormatError` rather than returning a page with holes in it.

    ``created`` is stringified rather than kept as whatever YAML inferred: an unquoted
    ``created: 2026-09-03`` loads as a ``date`` object, and letting that through would make the
    field's type depend on how the author quoted it.

    EVERY FIELD IS VALIDATED HERE, NOT ONLY ON WRITE — ``slug`` INCLUDED. Pages are agent-authored
    and land on disk by routes this module does not own (a backfill, an editor, a copy). The reader
    is the only place every page passes through, so it is where ``lane``'s path shape, the
    control-character rule and the frontmatter size cap are enforced.

    ``slug`` was the field that made that sentence false. On this path it is not frontmatter — it
    is the FILENAME, handed in by :func:`read_pages` — and :func:`render_projection` emits it
    verbatim, so a page whose filename carried a newline rendered three lines of ``hot.md`` where
    one entry belongs, planted directive included, sorted wherever its ``created`` put it. It is
    now held to :func:`_validated_slug`: the component rule, per path SEGMENT, because a nested
    page legitimately reads as ``lessons/deep``.
    """
    slug = _validated_slug(slug)
    match = _FRONTMATTER_RE.match(text)
    if not match:
        raise WikiFormatError(f"No YAML frontmatter found in page {slug!r}")

    if len(match.group(1)) > MAX_FRONTMATTER_CHARS:
        raise WikiFormatError(
            f"Frontmatter of page {slug!r} is {len(match.group(1))} chars, over the "
            f"{MAX_FRONTMATTER_CHARS} cap; refusing to load it"
        )

    try:
        data = yaml.safe_load(match.group(1))
    except yaml.YAMLError as exc:
        raise WikiFormatError(f"Unparseable frontmatter in page {slug!r}: {exc}") from exc

    if data is None:
        data = {}
    if not isinstance(data, dict):
        raise WikiFormatError(
            f"Frontmatter of page {slug!r} must be a mapping, got {type(data).__name__}"
        )

    title = _required_str(data, "title", slug)
    created = _validated_created(_required_str(data, "created", slug), slug)

    raw_lane = data.get("lane")
    lane = _scalar_text(raw_lane, "lane", slug) if raw_lane is not None else ""
    # A blank `lane:` means the page belongs to the project, not to a lane. A non-blank one is a
    # path component in `hot-<lane>.md` and is held to the same rule as `slug`.
    lane = _validated_component(lane, "lane", slug) if lane else None

    body = text[match.end() :]
    return Page(
        slug=slug,
        title=title,
        lane=lane,
        created=created,
        body=body,
        links=extract_links(body),
    )


def _scalar_text(value: object, key: str, slug: str) -> str:
    """One frontmatter value as a stripped, control-free, bounded string. Anything else raises.

    THE ``str()`` IS THE DANGEROUS PART, so the type check comes first. ``str()`` of a mapping or
    a list is a repr, and a repr of an aliased YAML node is the expansion of every alias under it
    — the amplification. A container in ``title``/``created``/``lane`` is malformed input; there
    is no reading of it that wants its repr in a hot file.
    """
    if isinstance(value, (dict, list, tuple, set, frozenset, bytes, bytearray)):
        raise WikiFormatError(
            f"Page {slug!r} frontmatter field {key!r} must be a scalar, "
            f"got {type(value).__name__}"
        )
    text = str(value)
    if len(text) > MAX_FIELD_CHARS:
        raise WikiFormatError(
            f"Page {slug!r} frontmatter field {key!r} is {len(text)} chars, "
            f"over the {MAX_FIELD_CHARS} cap"
        )
    text = text.strip()
    if _CONTROL_RE.search(text):
        raise WikiFormatError(
            f"Page {slug!r} frontmatter field {key!r} carries a newline or control character: "
            f"{text!r} - it would fabricate lines in a rendered hot file"
        )
    return text


def _required_str(data: dict, key: str, slug: str) -> str:
    """One field, present and non-empty, as a string — or a named error naming both."""
    value = data.get(key)
    if value is None:
        raise WikiFormatError(f"Page {slug!r} is missing required frontmatter field {key!r}")
    text = _scalar_text(value, key, slug)
    if not text:
        raise WikiFormatError(f"Page {slug!r} has an empty frontmatter field {key!r}")
    return text


def _validated_component(value: str, key: str, slug: str) -> str:
    """One path-forming field as a BARE filename component, or a loud error naming both.

    ``lane`` is agent-authored frontmatter that :func:`refresh_projection` interpolates into
    ``wiki_root / f"hot-{lane}.md"``. A page carrying ``lane: ../../../status/registry`` therefore
    made the refresh atomically overwrite the fleet's registry — lock-free, no error, from a file a
    lane wrote itself. The forced ``.md`` suffix is not a mitigation: ``CLAUDE.md`` and every
    ``SKILL.md`` end in ``.md``, so the reachable targets include the instructions the whole fleet
    reads at wake. That makes it instruction injection, not just data loss.

    ``slug`` is held to the same rule — on write directly, and on read one path segment at a time
    through :func:`_validated_slug`. (An earlier version of this docstring claimed ``slug`` "was
    validated from the start"; it was validated on the WRITE path from the start, and pages arrive
    by routes that never call the writer. A docstring asserting a property the code lacks is how
    the next reader inherits the bug, so it is worth saying which half was true.)

    Rejected, each for its own reason:

    * ``/`` and ``\\`` — the traversal itself.
    * ``:`` — the drive-relative form ``Z:evil``, which is neither absolute nor separator-bearing
      and still resolves outside the wiki whenever the drive differs from the root's.
    * ``|``, ``?``, ``*``, ``<``, ``>``, ``"`` — legal on POSIX, ILLEGAL in a Windows filename.
      They are not a traversal, they are a CRASH: the name passes every rule above, and then
      ``mkstemp`` inside ``_write_projection`` raises ``OSError`` partway through the refresh.
      That both fails the run and skips the stale sweep, so the projection is left half-rewritten
      with the previous run's files still asserting their own freshness.
    * a leading ``.`` — ``..`` and dotfiles, which ``read_pages`` would not see again.
    * control characters — a NUL truncates the name at the OS boundary, the rest fabricate lines.
    * Windows device names — see :data:`_RESERVED_STEMS`.
    * more than :data:`MAX_COMPONENT_BYTES` — a name no filesystem holds is a crash like the
      Windows-illegal characters, at the same point in the refresh.

    NOT rejected here, and worth knowing: ``Lesson`` and ``lesson`` are one file on Windows and two
    on Linux. That is a property of a PAIR of values, so a single-value rule cannot see it;
    :func:`refresh_projection` catches the case that matters — two lanes colliding on one file —
    and :func:`check_new_lane` refuses a new page that would create that pair.
    """
    if not value:
        raise WikiFormatError(f"Page {slug!r} has an empty {key} - it must be a bare name")
    if _CONTROL_RE.search(value):
        raise WikiFormatError(
            f"Page {slug!r} has {key}={value!r} carrying a control character"
        )
    if "/" in value or "\\" in value or ":" in value:
        raise WikiFormatError(
            f"Page {slug!r} has {key}={value!r}; it must be a bare filename component "
            f"(no '/', '\\' or ':') - it is interpolated straight into a path"
        )
    illegal = sorted(set(value) & _WINDOWS_ILLEGAL_CHARS)
    if illegal:
        raise WikiFormatError(
            f"Page {slug!r} has {key}={value!r}; {''.join(illegal)!r} cannot appear in a Windows "
            f"filename, so it does not fail validation, it crashes the write half way through"
        )
    if value.startswith("."):
        raise WikiFormatError(f"Page {slug!r} has {key}={value!r}; a bare name cannot start '.'")
    if value.split(".")[0].lower() in _RESERVED_STEMS:
        raise WikiFormatError(
            f"Page {slug!r} has {key}={value!r}; that is a reserved Windows device name and "
            f"writing it discards the bytes instead of creating a file"
        )
    size = len(value.encode("utf-8", "surrogatepass"))
    if size > MAX_COMPONENT_BYTES:
        raise WikiFormatError(
            f"Page {slug!r} has {key}={value[:40]!r}... of {size} bytes, over the "
            f"{MAX_COMPONENT_BYTES}-byte cap; it becomes a filename, and a filesystem refuses one "
            f"that long"
        )
    return value


def _validated_slug(slug: str) -> str:
    """A read-side ``slug`` — one or more path SEGMENTS, each a bare component. Returns it.

    NOT the same rule as the writer's, deliberately. ``read_pages`` walks ``pages/`` recursively
    and reports ``lessons/deep`` for ``pages/lessons/deep.md``, so a bare-component rule here would
    reject the module's own legitimate output. Splitting on ``/`` and holding each segment to
    :func:`_validated_component` keeps every reason that rule exists — ``..``, a drive letter, a
    device name, a Windows-illegal character, a control character — while allowing the nesting.

    Why the reader needs this at all: the slug is the one rendered field that is not frontmatter,
    so none of the frontmatter checks ever saw it, and :func:`render_projection` emits it verbatim
    into a line-oriented file. A filename may legally contain a newline on POSIX, and one that did
    turned a single hot-file entry into three lines — including a free-standing directive line —
    at whatever rank its ``created`` earned. An empty segment (``a//b``, a trailing ``/``) is
    rejected by the same call, which is also what stops an absolute-looking slug.
    """
    if not slug:
        raise WikiFormatError("a page slug cannot be empty")
    if _CONTROL_RE.search(slug):
        raise WikiFormatError(
            f"Page slug {slug!r} carries a newline or control character; it is rendered verbatim "
            f"into a line-oriented hot file, where it would fabricate lines"
        )
    for segment in slug.split("/"):
        _validated_component(segment, "slug", slug)
    return slug


def _validated_created(created: object, slug: str) -> str:
    """``created`` as ``YYYY-MM-DD``, or a loud error naming the page and the bad value.

    ENFORCED ON BOTH SIDES — :func:`parse_page` on read and :func:`write_page` on write — because
    a shape rule applied to only one of them is a rule about who wrote the page, not about what
    the page says. A backfill hands this module heterogeneous vault frontmatter (``yesterday``,
    ``09/01/2026``); ranking is a lexicographic compare, so anything that is not this shape sorts
    against real dates and produces a WRONG hot file rather than an exception. Shape only: no
    calendar check, no ``date`` object, no clock — ``2026-13-45`` is a date this module has no
    business having an opinion about, and it still sorts correctly among its neighbours.

    THE SHAPE ANCHOR IS NOT THE ONLY GUARD, because on the write path it was the only guard.
    Every other written field goes through :func:`_scalar_text`; ``created`` went straight from the
    caller's argument to ``yaml.safe_dump``, so ``_CREATED_RE``'s ``\\Z`` was single-handedly
    holding a newline out of the file — relax it to ``$`` and ``created: "2026-09-01\\n"`` is
    written to disk with every test still green. A control check that names the field is both a
    better error and a rule that does not evaporate when someone edits a regex.
    """
    if not isinstance(created, str):
        # The reader hands this a string already; a caller of `write_page` can hand it anything,
        # and a container here would reach `yaml.safe_dump` as frontmatter structure.
        created = _scalar_text(created, "created", slug)
    if _CONTROL_RE.search(created):
        raise WikiFormatError(
            f"Page {slug!r} has created={created!r} carrying a newline or control character; "
            f"it would fabricate lines in a rendered hot file"
        )
    if not _CREATED_RE.match(created):
        raise WikiFormatError(
            f"Page {slug!r} has created={created!r}; expected YYYY-MM-DD "
            f"(ordering is a lexicographic compare, so another shape ranks wrong silently)"
        )
    return created


# --------------------------------------------------------------------------- #
# Read side (IMPURE: filesystem only — no clock, no lock)
# --------------------------------------------------------------------------- #
def read_pages(wiki_root: Path) -> list[Page]:
    """Every LIVE page under ``wiki_root/pages/``, in sorted-path order.

    ``done/`` and ``archived/`` are skipped: they are terminal partitions, not live pages, and a
    projection that carried them would rank retired knowledge against current knowledge.

    A missing ``pages/`` is not an error — a project can have a wiki pillar before it has
    learned anything. A page that will not parse IS an error and propagates: a wiki that
    silently drops the one malformed page is a wiki whose hot file is quietly short.

    THE ERROR CARRIES THE PATH — INCLUDING THE DECODE ERROR. Propagating is only useful if the
    reader can act on it: because one unparseable page blocks every projection for the whole
    project until it is fixed, "which file" is the entire content of the report. A bare field error
    names a slug; this names a path a human can open. ``UnicodeDecodeError`` used to escape this
    wrapper untouched, so the one failure whose message named NO file at all was the one a human
    could not fix by reading the message.

    DECODED AS ``utf-8-sig``, NOT ``utf-8``. Every Windows editor and every PowerShell redirect
    writes a BOM; ``utf-8`` decodes it into a leading U+FEFF, the anchored ``_FRONTMATTER_RE.match``
    then fails, and ONE BOM'd page blocks ``hot.md`` and every ``hot-<lane>.md`` for the project.
    ``utf-8-sig`` strips a BOM if present and decodes plain UTF-8 unchanged, so this costs nothing
    on the files that never had one.
    """
    return [_read_one_page(path, rel) for path, rel in _live_page_files(wiki_root)]


def _live_page_files(wiki_root: Path) -> list[tuple[Path, Path]]:
    """``(path, path relative to pages/)`` for every live page file, sorted. The one walk."""
    pages_dir = wiki_root / PAGES_DIRNAME
    if not pages_dir.is_dir():
        return []
    out: list[tuple[Path, Path]] = []
    for path in sorted(pages_dir.rglob("*.md")):
        rel = path.relative_to(pages_dir)
        if TERMINAL_PARTITIONS.intersection(rel.parts[:-1]):
            continue
        out.append((path, rel))
    return out


def _read_one_page(path: Path, rel: Path) -> Page:
    """Parse one page file; any failure is a :class:`WikiFormatError` naming *path*."""
    try:
        text = path.read_text(encoding="utf-8-sig")
    except UnicodeDecodeError as exc:
        raise WikiFormatError(f"{path}: not valid UTF-8 ({exc})") from exc
    try:
        return parse_page(text, slug=rel.with_suffix("").as_posix())
    except WikiFormatError as exc:
        raise WikiFormatError(f"{path}: {exc}") from exc


# --------------------------------------------------------------------------- #
# Read-side projections (PURE: no clock, no file, no lock — the caller only writes them)
# --------------------------------------------------------------------------- #
# THE PROJECTION NEEDS NO LOCK because it is a pure function of the page set: two lanes running
# `refresh_projection` at the same moment over the same pages compute the same bytes, so the
# interleaving cannot produce a state neither of them intended. What serialises the only write
# that matters is `atomic_write` (temp + fsync + replace), which a reader can never catch
# half-done. A lock here would buy nothing and would put a fleet-wide stall behind a rendering.
def select(
    pages: Sequence[Page],
    *,
    limit: int = DEFAULT_TOP_N,
    lane: str | None = None,
) -> list[Page]:
    """The top *limit* pages, newest ``created`` first, ties broken by ``slug`` ascending.

    ONE FUNCTION SERVES BOTH HOT LEVELS. ``lane=None`` selects across every page (the
    project-wide level); a lane keeps only pages declaring it. A second code path for the
    per-lane case would be two rankings that drift, and the drift would show up as two hot files
    disagreeing about the same page — which nobody would read as a bug.

    Ordering is total and independent of the input order, so it never inherits the filesystem's
    directory order. The two-pass sort is deliberate: sort by slug ascending, then by ``created``
    descending, and Python's stable sort leaves the slug order intact inside each date.
    """
    if limit < 0:
        raise ValueError(f"limit must be >= 0, got {limit}")

    candidates = [p for p in pages if lane is None or p.lane == lane]
    by_slug = sorted(candidates, key=lambda p: p.slug)
    ordered = sorted(by_slug, key=lambda p: p.created, reverse=True)
    return ordered[:limit]


def render_projection(pages: Sequence[Page], *, lane: str | None = None) -> str:
    """The markdown body of a hot file for an ALREADY-SELECTED page sequence. PURE.

    Emits each page's own ``[[wikilinks]]`` alongside a link to the page itself. The hot file is
    the densest thing a lane reads at wake, so it is also the cheapest place for the page graph
    to stay visible; flattening the edges to plain titles here would make the future graph a
    re-parse of every page instead of a read of one file.

    *lane* names the file being rendered; it must AGREE with the pages handed in. Selection and
    rendering are two calls, so a caller can pair one lane's pages with another lane's heading —
    ``render_projection(select(pages, lane="a"), lane="b")`` — and the result is a well-formed
    file, correctly banner-marked, headed ``b`` and listing ``a``'s pages. Nothing downstream
    could catch that, so it raises here.

    EVERY EMITTED FIELD IS CHECKED CONTROL-FREE AT THE EMIT SITE. ``title``, ``lane`` and link
    targets earn that upstream, and ``slug`` now does too (:func:`_validated_slug`) — but this is
    the line that turns a value into a LINE, and a rule whose only home is upstream of the
    dangerous line is a rule someone can route around later. A hand-built :class:`Page` never
    passed the reader. The check is a scan of already-parsed strings: no clock, no file, no lock,
    so the purity guarantee is intact.
    """
    fabricated = sorted(
        {
            value
            for page in pages
            for value in (page.slug, page.title, page.created, *page.links)
            if _CONTROL_RE.search(value)
        }
    )
    if fabricated:
        raise ValueError(
            f"render_projection was handed field(s) carrying a newline or control character: "
            f"{fabricated!r}; a hot file is line-oriented, so each one fabricates lines in it"
        )

    if lane is not None:
        mismatched = sorted({p.lane for p in pages if p.lane != lane})
        if mismatched:
            raise ValueError(
                f"render_projection(lane={lane!r}) was handed page(s) from lane(s) "
                f"{mismatched!r}; the heading would contradict the entries under it"
            )

    heading = f"# Hot - {lane}" if lane else "# Hot"
    scope = f"lane `{lane}`" if lane else "project-wide"

    lines = [
        heading,
        "",
        GENERATED_MARKER,
        "",
        f"{len(pages)} page(s), {scope}, newest first.",
        "",
    ]
    if not pages:
        lines.append("_No pages yet._")
    else:
        for page in pages:
            entry = f"- [[{page.slug}]] - {page.title} ({page.created})"
            if page.links:
                entry += " -> " + ", ".join(f"[[{target}]]" for target in page.links)
            lines.append(entry)
    return "\n".join(lines) + "\n"


#: What a scaffolded, never-yet-written ``digest.md`` says about itself.
#:
#: The whole reason the file is created empty rather than left absent: an ABSENT file cannot tell
#: a reader "no sweep has run yet" from "the pillar is broken", and the reader that opens it first
#: is the one seat with no other way to find out. So the placeholder answers that question in
#: words, and names the seat that will replace it.
EMPTY_DIGEST_NOTE = (
    "_No digest yet. The steward is this file's only writer and regenerates it at the end of "
    "every sweep. This placeholder means no sweep has run for this project yet - it does NOT "
    "mean the pillar is broken. dev-manager reads this file at session start and never writes "
    "it (Q-10036)._"
)


def initial_pillar_files(project: str) -> dict[str, str]:
    """The ``wiki/`` files a freshly provisioned project carries, ``filename -> body``. PURE.

    ONE DEFINITION OF "A VALID EMPTY PILLAR", AND THE PROVISIONER IMPORTS IT. ``hot.md``'s body
    here is not a copy of what an empty projection looks like — it is
    :func:`render_projection` called on no pages, the same call :func:`refresh_projection` makes,
    so the scaffolded file is byte-identical to the one the first refresh replaces it with. A
    second, hand-typed "empty hot file" living in ``install/provision.py`` is precisely the defect
    this function exists to prevent: it would drift the day the projection's banner, heading or
    count line changes, and the drift would show up as a scaffolded file that quietly contradicts
    every refreshed one.

    WHY THESE FILES EXIST AT ALL BEFORE ANYTHING HAS RUN. Both are READ before they are written:
    a lane opens ``hot.md`` at wake and dev-manager opens ``digest.md`` at session start. Until
    something happened to run a refresh or a steward sweep, neither existed, and a reader finding
    nothing there cannot distinguish *"no lessons yet"* from *"the pillar is broken"* — the one
    signal that has no fallback. Creating them with valid empty bodies makes the first state
    legible and leaves the second reportable.

    ``hot-<lane>.md`` is deliberately NOT here. A lane file is evidence that a lane has written a
    page; scaffolding one would assert a lane that does not exist, and the next refresh's stale
    sweep would delete it anyway.

    *project* names the fleet in the digest's heading, so a digest opened out of context says
    whose it is. It is checked control-free at this emit site — the same rule
    :func:`render_projection` applies to every field it turns into a line — because a project name
    reaches here from a config filename, and a name carrying a newline would fabricate lines in a
    file a human reads as a report.
    """
    if not project or not project.strip():
        raise ValueError("project must be a non-empty name; it heads the scaffolded digest")
    if _CONTROL_RE.search(project):
        raise ValueError(
            f"project {project!r} carries a newline or control character; it is interpolated into "
            f"the digest heading, so it would fabricate lines in a file a human reads"
        )
    return {
        HOT_FILENAME: render_projection((), lane=None),
        DIGEST_FILENAME: f"# {project} - fleet digest\n\n{EMPTY_DIGEST_NOTE}\n",
    }


def missing_pillar_markers(wiki_root, *, require_hot: bool = True) -> list[str]:
    """The provisioned-pillar markers *wiki_root* lacks; ``[]`` means it is a pillar. NEVER raises.

    gh#501. A save handed the wrong root used to succeed: ``write_page`` makes ``pages/`` with
    ``mkdir(parents=True)``, so ANY directory - or a mistyped path that did not exist - became a
    store, and the page landed where no reader looks. A writer calls this first and refuses on a
    non-empty answer.

    THE MARKERS, and why each is here. ``digest.md`` is the one that decides it: every other
    marker was present at the root of the mis-aimed save's target (the mis-aim itself left a
    GENERATED ``hot.md`` and a ``pages/`` behind), and only a provisioned pillar carries a digest.
    ``hot.md`` must carry :data:`GENERATED_MARKER`, which separates a pillar from a directory whose
    ``hot.md`` is a hand-written cache. ``pages/`` is the store itself.

    EXISTENCE ONLY, never content, except the one marker line. The steward rewrites ``digest.md``
    on every sweep, and a content check would fail every save the first time its wording moved.
    The shape checked is exactly what :func:`initial_pillar_files` plus ``pages/`` lays down, so
    the provisioner and this check share one definition.

    ``require_hot=False`` drops every ``hot.md`` condition (gh#521) and is the refresh CLI's gate:
    refresh is the only tool that regenerates ``hot.md``, so requiring a good one there would
    refuse the repair of a deleted, hand-edited or re-encoded file. ``digest.md`` still decides.
    """
    root = Path(wiki_root)
    if not root.is_dir():
        return [f"{root} (the directory itself)"]
    missing: list[str] = []
    if not (root / DIGEST_FILENAME).is_file():
        missing.append(DIGEST_FILENAME)
    if require_hot:
        missing.extend(_missing_hot_markers(root / HOT_FILENAME))
    if not (root / PAGES_DIRNAME).is_dir():
        missing.append(f"{PAGES_DIRNAME}/")
    return missing


def _missing_hot_markers(hot: Path) -> list[str]:
    """The ``hot.md`` half of :func:`missing_pillar_markers`. NEVER raises."""
    if not hot.is_file():
        return [HOT_FILENAME]
    try:
        if GENERATED_MARKER not in hot.read_text(encoding="utf-8"):
            return [f"{HOT_FILENAME}'s GENERATED marker"]
    except (OSError, UnicodeDecodeError) as e:
        return [f"a readable {HOT_FILENAME} ({type(e).__name__}: {e})"]
    return []


def _not_a_pillar(root: Path, missing: Sequence[str], via: str) -> NotAPillarError:
    return NotAPillarError(
        f"{root} is not a provisioned wiki pillar ({via}): missing {', '.join(missing)}; "
        f"re-provision the project (install/provision.py) rather than creating these by hand"
    )


# --------------------------------------------------------------------------- #
# Write side (IMPURE: filesystem only — no clock, no lock)
# --------------------------------------------------------------------------- #
def _refresh(wiki_root: Path, *, limit: int = DEFAULT_TOP_N) -> tuple[list[Path], list[Path]]:
    """Regenerate ``hot.md`` and one ``hot-<lane>.md`` per lane. Returns (current, changed).

    A thin wrapper by design: it reads, it ranks with :func:`select`, it renders with
    :func:`render_projection`, it writes. It owns NO ranking and NO rendering of its own, so the
    file on disk cannot disagree with what a caller computes in memory from the same pages.

    Lanes come from the whole live page set, not from the project-wide top-N: a lane whose best
    page sits at rank 40 still gets its own hot file, which is the entire point of having one.

    THE SWEEP IS PART OF THE REGENERATION, not tidying. Retiring a page is a move into
    ``pages/done/`` — routine, and the documented mechanism — so a lane losing its last live page
    is an ordinary Tuesday. Without the sweep its ``hot-<lane>.md`` survives, still listing the
    retired page, under a banner promising the next refresh overwrites it. A stale file that
    asserts its own freshness is worse than no file: nobody re-reads a hot file to check it. The
    sweep is scoped to the names this function writes (``hot.md``, ``hot-<lane>.md``) and touches
    nothing else in the directory — ``digest.md`` is the steward's and survives.

    IT REFUSES BEFORE IT WRITES ANYTHING. See :func:`_check_lane_filenames`: the lane set is
    checked whole ahead of the first ``atomic_write``, because a refusal halfway through leaves
    ``hot.md`` fresh, some lane files stale, and the sweep unrun — a worse state than not having
    run at all, and one that asserts its own freshness in every file.

    A missing *wiki_root* RAISES. The provisioner creates this directory with the project; a root
    that is not there is a typo or an unprovisioned project, and ``mkdir(parents=True)`` would
    answer a typo by fabricating a tree and writing a valid-looking empty ``hot.md`` into it —
    a wrong answer that looks exactly like a right one.
    """
    if not wiki_root.is_dir():
        raise FileNotFoundError(
            f"wiki root {wiki_root} does not exist; it is created with the project, so a missing "
            f"one is an unprovisioned project or a mistyped path, not a directory to create here"
        )

    pages = read_pages(wiki_root)

    lanes = sorted({p.lane for p in pages if p.lane})
    lane_pages = _lane_pages(wiki_root, pages)
    _check_lane_filenames(lanes, lane_pages)
    _check_paths_fit(_projection_targets(wiki_root, lanes, lane_pages))

    # TWO SETS, NOT ONE, and conflating them deletes files (gh#364). `current` is every path the
    # projection should have; `changed` is the subset this run actually rewrote. The stale sweep
    # below needs `current` -- anything not in it is unlinked -- so narrowing the single old
    # `written` list to the files that changed would have deleted exactly the ones the new skip
    # left alone. One name serving two predicates parts company the moment the sets differ.
    current: list[Path] = []
    changed: list[Path] = []

    def _do(path: Path, lane: str | None) -> None:
        current.append(path)
        if _write_projection(path, pages, limit=limit, lane=lane):
            changed.append(path)

    _do(wiki_root / "hot.md", None)
    for lane in lanes:
        # Defence in depth at the path-forming site. `parse_page` already refused a traversing
        # lane, but THIS is the line that turns a lane into a filesystem path, and a rule whose
        # only home is upstream of the dangerous line is a rule someone can route around later.
        _validated_component(lane, "lane", next(p.slug for p in pages if p.lane == lane))
        _do(wiki_root / f"hot-{lane}.md", lane)

    fresh = {path.name for path in current}
    for stale in sorted(wiki_root.glob(_HOT_LANE_GLOB)):
        if stale.name not in fresh and stale.is_file():
            stale.unlink()
    return current, changed


def _check_lane_filenames(lanes: Sequence[str], lane_pages: Mapping[str, Sequence[str]]) -> None:
    """Refuse a lane set that cannot become one file per lane. Raises before anything is written.

    Two failures, both checked BEFORE the first write, because a refresh that dies partway leaves
    ``hot.md`` rewritten, some lane files fresh, others from the previous run, and the stale sweep
    unrun — every one of them still carrying the banner that promises otherwise.

    * A lane that is not a bare component (traversal, device name, Windows-illegal character).
    * A CASE COLLISION. ``Lead`` and ``lead`` are two lanes to a Python set and one file on
      Windows: the second write silently overwrites the first, and this function returns BOTH
      paths, so the CLI prints a path whose content belongs to the other lane. Neither lane is
      wrong on its own, so the error has to name the pair — and it fires on every platform,
      because a vault is authored on one and read on the other.

    THE ERROR NAMES THE PAGES, not just the lanes. A lane is not a file anyone can open; the fix
    is to retire the pages of one spelling, so the message lists every page carrying each.
    """
    seen: dict[str, str] = {}
    for lane in lanes:
        _validated_component(lane, "lane", lane_pages[lane][0])
        first = seen.setdefault(lane.casefold(), lane)
        if first != lane:
            raise WikiFormatError(
                f"lanes {first!r} (pages: {', '.join(lane_pages[first])}) and {lane!r} (pages: "
                f"{', '.join(lane_pages[lane])}) differ only by case; they are two lanes here and "
                f"ONE file (hot-{lane}.md) on a case-insensitive filesystem, so one projection "
                f"would silently overwrite the other and both paths would be reported as written. "
                f"Retire one spelling by moving its pages into {PAGES_DIRNAME}/archived/, which "
                f"refresh does not read."
            )


def _path_limit() -> int | None:
    """The longest absolute path this platform will open, or None when only a name is bounded.

    Windows caps a WHOLE path at 259 characters unless long paths are enabled machine-wide, so a
    component that fits a filename can still fail to open under a deep root. The registry value
    is read rather than assumed either way: absent means disabled, which is Windows' default.
    """
    if os.name != "nt":
        return None
    import winreg

    try:
        with winreg.OpenKey(
            winreg.HKEY_LOCAL_MACHINE, r"SYSTEM\CurrentControlSet\Control\FileSystem"
        ) as key:
            enabled, _ = winreg.QueryValueEx(key, "LongPathsEnabled")
    except FileNotFoundError:
        enabled = 0
    return None if enabled == 1 else _WINDOWS_MAX_PATH


def _check_paths_fit(targets: Sequence[tuple[Path, int, str]]) -> None:
    """Refuse when any ``(path, temp_extra, page)`` would be over :func:`_path_limit`.

    ``temp_extra`` is how much longer the temp file written first is, because that is the name
    that fails. Called before the first write, so a refusal leaves every file as it was.
    """
    limit = _path_limit()
    if limit is None:
        return
    for path, extra, page in targets:
        # Windows counts UTF-16 units, and a character outside the BMP is two of them.
        size = len(os.path.abspath(path).encode("utf-16-le")) // 2 + extra
        if size > limit:
            raise WikiFormatError(
                f"{page}: {path.name[:60]!r} would be written as a {size}-character path "
                f"(counting its temp file), over this platform's {limit}-character limit; "
                f"shorten the slug or lane, move the data root shallower, or enable long paths"
            )


def _projection_targets(
    wiki_root: Path, lanes: Sequence[str], lane_pages: Mapping[str, Sequence[str]]
) -> list[tuple[Path, int, str]]:
    """Every file a refresh writes, with the page each one is on account of."""
    out = [(wiki_root / HOT_FILENAME, _ATOMIC_TEMP_EXTRA, "the project projection")]
    for lane in lanes:
        out.append(
            (wiki_root / f"hot-{lane}.md", _ATOMIC_TEMP_EXTRA, f"page {lane_pages[lane][0]}")
        )
    return out


def _lane_pages(wiki_root: Path, pages: Sequence[Page]) -> dict[str, list[str]]:
    """Each lane carried by *pages*, mapped to the on-disk path of every page carrying it."""
    out: dict[str, list[str]] = {}
    for p in pages:
        if p.lane:
            out.setdefault(p.lane, []).append(str(Path(wiki_root) / PAGES_DIRNAME / f"{p.slug}.md"))
    return out


def check_new_lane(wiki_root: Path, lane: object, *, page: str = "the page being saved") -> str:
    """Refuse a lane a NEW page may not carry. Returns the validated lane.

    The single-value rules (:func:`_validated_component`) plus the case rule refresh applies
    (``casefold``): *lane* differing only by case from a lane already carried by a LIVE page.
    "Live" is the same walk :func:`read_pages` makes — pages under ``pages/done/`` and
    ``pages/archived/`` are skipped by both, so the writer and the refresh agree on which lanes
    exist.

    ONLY THE NEW LANE IS JUDGED. A case pair already on disk is refresh's to report — it names
    every page and the ``archived/`` remedy — and refusing every laned write until someone moves
    pages would turn one bad pair into a store nobody can save to.

    A PAGE THAT WILL NOT PARSE IS SKIPPED HERE, not raised. It carries no readable lane to collide
    with, and raising would lose every laned save for as long as it sits there. It is not hidden:
    the refresh that follows every write reads the same page and fails naming its path.

    Public so ``save_summariser.compose_and_save`` can refuse before it spends a model call;
    :func:`write_page` calls it too, so the rule has one home.
    """
    wiki_root = Path(wiki_root)
    lane = _validated_component(_scalar_text(lane, "lane", page), "lane", page)
    pages: list[Page] = []
    for path, rel in _live_page_files(wiki_root):
        try:
            pages.append(_read_one_page(path, rel))
        except WikiFormatError:
            continue  # refresh reports it by path; see the docstring
    lane_pages = _lane_pages(wiki_root, pages)
    twins = sorted(
        other for other in lane_pages if other != lane and other.casefold() == lane.casefold()
    )
    if twins:
        found = "; ".join(f"{t!r} (pages: {', '.join(lane_pages[t])})" for t in twins)
        raise WikiFormatError(
            f"lane {lane!r} for {page} and live lane(s) {found} differ only by case; they would "
            f"be ONE file (hot-{lane}.md) on a case-insensitive filesystem, and refresh refuses "
            f"the pair for the whole project. Use the existing spelling of the lane."
        )
    return lane


def refresh_projection(wiki_root: Path, *, limit: int = DEFAULT_TOP_N) -> list[Path]:
    """Regenerate the hot projection. Returns the projection's CURRENT file set.

    Deliberately NOT "the files this run rewrote" (gh#364). Since the write became conditional
    those are different lists, and this one is the contract every caller already depends on:
    `save_summariser` ignores it, the CLI prints it, and the stale sweep inside `_refresh` uses
    it to decide what to unlink. A returned path may not have been touched this run -- ask
    `_refresh` when you need to know which changed, as the CLI does.
    """
    return _refresh(wiki_root, limit=limit)[0]


def _write_projection(path: Path, pages: Sequence[Page], *, limit: int, lane: str | None) -> bool:
    """Select + render + atomically replace one hot file IF the rendering differs. Wrote?

    UNCONDITIONAL BEFORE gh#364, and the cost was a lie in the only timestamp these files carry.
    `atomic_write` is temp + fsync + replace, so it touches the inode every run whatever the
    bytes say; measured on the live tree, eight files came back byte-identical with eight
    advanced mtimes. A `hot*.md` mtime then answers "when did the steward last sweep", never
    "when did this lane's projection last change", and only the second question is useful to a
    watcher, a backup or a freshness check.

    The suite had already ruled on this shape three times - `issue_intake.write_if_changed`
    skips and says so, `agentflow.backups` distinguishes a removal from a refusal, and
    `registry.status --heartbeat-only` exists so a re-stamp cannot overwrite unchanged columns.
    The projection was the odd one out.

    COMPARED AS BYTES, WHICH IS BOTH READS THIS NEEDED. `atomic_write` writes utf-8 with
    ``newline=""`` -- verbatim, preserving the caller's line endings -- so the bytes on disk are
    ``body.encode("utf-8")`` exactly, and comparing them settles two questions at once:

    * a universal-newlines TEXT read would translate CRLF on the way in, so a file whose endings
      drifted would compare equal to the LF rendering, be skipped, and stay drifted forever. The
      byte comparison sees the difference and heals it.
    * a text read of any encoding raises ``UnicodeDecodeError`` on a corrupt file -- a
      ``ValueError``, NOT an ``OSError`` -- which would sail past the guard below, wedge the
      refresh permanently, and strand the run with ``hot.md`` rewritten and the stale sweep
      unrun. It would also break `_check_lane_filenames`' promise that this function "raises
      before anything is written". Reading bytes cannot raise it at all.
    """
    body = render_projection(select(pages, limit=limit, lane=lane), lane=lane)
    if path.exists():
        try:
            existing = path.read_bytes()
        except OSError:
            # Unreadable is not "unchanged": fall through and write, which is what restores a
            # file whose PERMISSIONS broke underneath us. Encoding is deliberately not named
            # here - bytes cannot fail to decode, which is why they are what is compared.
            existing = None
        if existing == body.encode("utf-8"):
            return False
    atomic_write(path, body)
    return True


def write_page(
    wiki_root: Path,
    *,
    slug: str,
    title: str,
    body: str,
    created: str,
    lane: str | None = None,
) -> Path:
    """Create ``wiki_root/pages/<slug>.md``. CREATION-ONLY. Returns the path written.

    Two refusals, both loud, both load-bearing:

    * **The page already exists** (:class:`PageExistsError`). Pages are create-only; a correction
      is a new page that links to the old one. Overwriting would silently rewrite the record of
      what was learned, and the projection is regenerated from pages, so nothing else would show
      the loss.
    * **The body carries no** ``[[wikilink]]`` (:class:`MissingWikilinkError`). Pages carry
      wikilinks from the FIRST page written. Retrofitting links onto hundreds of pages later is a
      migration; writing them as you go is free. Enforcing it in the writer is what makes the
      rule true rather than merely documented — a rule that lives only in prose is obeyed by
      whoever read the prose.

    And one on the root: **it is not a provisioned pillar** (:class:`NotAPillarError`, gh#521),
    checked after every field refusal and before anything is created. See
    :func:`missing_pillar_markers`.

    Further refusals, on the data rather than on the file, all raising :class:`WikiFormatError`
    and all the SAME rules the reader applies — see :func:`_validated_created`,
    :func:`_validated_component` and :func:`_scalar_text`. ``created`` must be ``YYYY-MM-DD``;
    ``slug`` and ``lane`` must be bare filename components; ``title`` must be a bounded,
    control-free string. Writing a page the reader would reject is a page that wedges every
    projection for the project the moment it lands, so the writer refuses to create one.

    That includes the one rule that is about a PAIR of values: a ``lane`` that differs only by
    case from a lane a live page already carries (see :func:`check_new_lane`). Refresh refuses
    that pair for the whole project, so the writer refuses it here, before the create. A live
    page that will not parse is skipped by this check, so it does not block a laned write; the
    refresh after the write names it. The check is not serialised against a concurrent write, so
    two simultaneous writes of twin spellings can both pass, and refresh then names the pair.

    THE CREATE IS EXCLUSIVE AT THE OS, NOT BY A CHECK. ``path.exists()`` followed by a write is a
    race whose loser is SILENT — ``os.replace`` overwrites unconditionally, so two writers racing
    the same slug end with one page and no error, which is precisely the silent rewrite the
    create-only rule exists to prevent. See :func:`_exclusive_create`.

    ``created`` is an argument, never a clock read: the caller knows what date the page is for
    (a backfill is not written "today"), and this module stays clock-free.

    **READ AND WRITE ARE NOT SYMMETRIC IN THE SLUG, DELIBERATELY.** ``read_pages`` walks
    ``pages/`` recursively and returns path-shaped slugs for nested pages — ``lessons/deep`` for
    ``pages/lessons/deep.md``. This writer accepts only a BARE component, so feeding a slug that
    came out of ``read_pages`` straight back in raises ``ValueError`` for any page that lives in
    a subdirectory. That is intended: the separator check is what stops ``../escape``, and there
    is no way to allow ``lessons/deep`` through it that does not also need a containment check
    this module has no reason to own yet. A caller writing into a nested folder should build the
    path itself; a backfill importing a vault that HAS folders will meet this, and meets it here
    in the docs rather than in a traceback partway through the import. ``slug`` is also
    case-preserving and case-INSENSITIVE on Windows only: ``Lesson`` and ``lesson`` are one page
    there and two on Linux, and this writer refuses the second only on the platform that collides.
    """
    slug = _validated_component(slug, "slug", slug)
    created = _validated_created(created, slug)
    title = _scalar_text(title, "title", slug)
    if not title:
        raise WikiFormatError(f"Page {slug!r} was given an empty title")
    if lane is not None:
        lane = _validated_component(_scalar_text(lane, "lane", slug), "lane", slug)

    path = wiki_root / PAGES_DIRNAME / f"{slug}.md"
    # `extract_links`, not a bare `_WIKILINK_RE.search`: `[[   ]]` MATCHES the pattern, so the
    # search said yes to a body whose only link is an edge to nothing — which the projection then
    # rendered as a literal `[[]]`. The requirement is a target, and the extractor is what decides
    # what counts as one.
    if not extract_links(body):
        raise MissingWikilinkError(
            f"Page {slug!r} carries no [[wikilink]]; every page links to at least one other"
        )

    front: dict[str, str] = {"title": title, "created": created}
    if lane is not None:
        front["lane"] = lane
    # safe_dump, not an f-string: a title carrying a colon or a quote must not be able to
    # fabricate frontmatter structure, and a bare ISO date must come back out a string,
    # not a `date`.
    block = yaml.safe_dump(front, sort_keys=False, allow_unicode=True, default_flow_style=False)

    # gh#521: the pillar check, AFTER every field refusal so a bad field is reported as itself,
    # and immediately before the first filesystem write. The full marker set, as
    # compose_and_save gates, so both writers accept exactly the same roots.
    missing = missing_pillar_markers(wiki_root)
    if missing:
        raise _not_a_pillar(Path(wiki_root), missing, "write_page")
    # The page, its temp file, and the lane file the refresh after this write will create: a
    # page accepted here whose lane file cannot be opened wedges every later refresh.
    targets = [(path, 0, f"page {path}"), (path.parent / _PAGE_TEMP_NAME, 0, f"page {path}")]
    if lane is not None:
        targets.append((Path(wiki_root) / f"hot-{lane}.md", _ATOMIC_TEMP_EXTRA, f"page {path}"))
    _check_paths_fit(targets)
    # The pair rule refresh applies, checked against the live pages before the create: a lane
    # that differs only by case from an existing one would wedge every refresh for the project.
    if lane is not None:
        check_new_lane(wiki_root, lane, page=str(path))
    # No `parents=True`: that is what turned any path into a store. pages/ was just verified, so
    # a root removed since raises here instead of being recreated.
    path.parent.mkdir(exist_ok=True)
    try:
        _exclusive_create(path, f"---\n{block}---\n{body}")
    except FileExistsError as exc:
        raise PageExistsError(
            f"Page {slug!r} already exists at {path}; pages are create-only"
        ) from exc
    return path


def _exclusive_create(path: Path, text: str) -> None:
    """Write *text* to *path*, atomically, and only if *path* does not already exist.

    Raises ``FileExistsError`` from the OS — never from a preceding ``exists()``, which is a
    check and not a guarantee. The two branches are the two platforms' ways of spelling the same
    primitive, and each is BOTH atomic and exclusive:

    * POSIX ``os.link`` fails if the destination exists (``os.rename`` there would overwrite).
    * Windows ``os.rename`` fails if the destination exists (``os.link`` there needs NTFS).

    The temp file is created in the destination's own directory so the link/rename is same-volume
    and therefore atomic, and it is named to fall outside ``read_pages``'s ``*.md`` walk, so a
    reader mid-write sees the page or nothing — never a partial one.
    """
    fd, tmp_name = tempfile.mkstemp(dir=str(path.parent), prefix=".wiki-", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(text.encode("utf-8"))
            handle.flush()
            os.fsync(handle.fileno())
        if os.name == "nt":
            os.rename(tmp_name, path)
        else:
            os.link(tmp_name, path)
    finally:
        try:
            os.unlink(tmp_name)
        except FileNotFoundError:
            pass  # consumed by a successful rename


# --------------------------------------------------------------------------- #
# CLI — how a loop skill invokes the refresh
# --------------------------------------------------------------------------- #
# WHY THIS EXISTS. `refresh_projection` is only a duty if something can call it. The steward's
# skill tells it to write `digest.md` "drawn from the wiki/ projection", and a skill invokes
# python, not a function object: without an entry point the projection and the duty ship as two
# disconnected halves, each looking complete on its own.
#
# --project RESOLUTION IS REGISTRY'S, NOT A SECOND ONE. `registry._resolve_registry_path` takes
# an explicit path first, else validates --project as a bare slug and joins it under
# `config.load_environment().data_root`. Same order and same slug rule here, with `wiki/` in
# place of `status/registry.md`; the slug regex is IMPORTED from registry rather than restated,
# so the two cannot drift into disagreeing about what a project name is.
def _resolve_wiki_root(a: argparse.Namespace) -> Path:
    """``--wiki-root`` if given, else ``<data_root>/projects/<project>/wiki``. Raises if absent.

    Either way the resolved root must be a provisioned pillar (gh#521): ``--wiki-root`` used to
    check only that the directory existed, so any directory became a refresh target. The gate
    omits ``hot.md`` on purpose - see :func:`missing_pillar_markers`.
    """
    if getattr(a, "wiki_root", None):
        root = Path(a.wiki_root)
        if not root.is_dir():
            raise FileNotFoundError(f"--wiki-root {root} does not exist")
        via = "--wiki-root"
    else:
        root = _resolve_project_wiki_root(a)
        via = f"--project {a.project}"
    missing = missing_pillar_markers(root, require_hot=False)
    if missing:
        raise _not_a_pillar(root, missing, via)
    return root


def _resolve_project_wiki_root(a: argparse.Namespace) -> Path:
    """``<data_root>/projects/<project>/wiki``, with registry's slug rule. Raises if absent."""

    project = getattr(a, "project", None)
    if not project:
        raise ValueError("no --wiki-root and no --project to derive a path from")

    # Lazy, exactly as registry does it: a caller driving this with --wiki-root (every test, and
    # any ad-hoc run outside a configured environment) must never be made to have a config.
    from . import config
    from .registry import _PROJECT_RE

    if not _PROJECT_RE.match(project):
        raise ValueError(
            f"project {project!r} must match [A-Za-z0-9_-]+ (no path separators or '..')"
        )

    # ValueError, so both `refresh` and `residue` refuse with exit 2 and a line, not a traceback.
    try:
        data_root = config.load_environment().data_root
    except (config.ConfigError, OSError, UnicodeDecodeError) as exc:
        raise ValueError(
            f"--project {project}: data_root not resolved: the environment config did not load: "
            f"{config.error_line(exc, config.environment_path())} (or pass --wiki-root)"
        ) from exc
    project_dir = Path(data_root) / "projects" / project
    if not project_dir.is_dir():
        raise FileNotFoundError(f"no project {project!r}: {project_dir} does not exist")
    root = project_dir / WIKI_DIRNAME
    if not root.is_dir():
        raise FileNotFoundError(
            f"project {project!r} has no wiki pillar: {root} does not exist "
            f"(it is created with the project; re-provision rather than mkdir it by hand)"
        )
    return root


def _build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="python -m agentflow.wiki",
        description="the wiki pillar: regenerate the hot projections from the live page set",
    )
    sub = p.add_subparsers(dest="command", required=True)

    sp = sub.add_parser("refresh", help="rewrite hot.md + hot-<lane>.md, and drop stale ones")
    sp.add_argument("--project", help="project routing key (derives the path via config)")
    sp.add_argument("--wiki-root", dest="wiki_root", help="explicit wiki/ path (wins over --project)")
    sp.add_argument(
        "--limit",
        type=int,
        default=DEFAULT_TOP_N,
        help=f"pages per projection (default {DEFAULT_TOP_N})",
    )

    # WHY `residue` LIVES ON THIS PARSER. It is the pillar's other read-only sweep, and this is
    # the command the steward already runs against the pillar every wake -- so it inherits the
    # same `--project` / `--wiki-root` resolution and the operator learns no second entry point.
    # The LOGIC is `agentflow.pillar_residue`, because that module reads a REPO file (`ci.yml`,
    # for the sanitize pattern it refuses to keep a second copy of) and this one is about the
    # data root; routing here and owning nothing keeps that split. The import is NOT lazy and
    # the comment used to claim it was: `_build_parser` runs on every invocation, including the
    # steward's per-wake `refresh`. It is cheap and side-effect-free at import (stdlib only, two
    # Paths computed), so the cost is real but negligible - which is worth saying plainly rather
    # than describing a laziness the call graph does not have.
    from . import pillar_residue

    pillar_residue.add_arguments(
        sub.add_parser(
            "residue",
            help="report residue in the live page set and ratchet it against a recorded baseline",
        )
    )
    return p


def main(argv: Sequence[str] | None = None) -> int:
    """Entry point. Prints one written path per line; non-zero WITH A MESSAGE on any failure.

    Two non-zero codes, and the split is the one a calling skill can act on:

    * **2 — the input was refused.** A page will not parse, a lane is not a filename, a project
      does not exist, the limit is negative, the environment config that ``--project`` needs
      will not load. Something in the vault or the config has to change.
    * **3 — the environment refused.** Any other ``OSError``: the hot file is read-only or held
      open, the volume is full, a path is too long. Nothing in the vault is wrong.

    Both were promised by the old docstring and only the first was delivered: ``PermissionError``
    on a locked hot file — an ordinary Windows outcome with an editor open on it — escaped the
    handler and dumped a traceback, which is the one output a skill parsing this cannot use.
    """
    # First, before any output: a legacy cp1252 stdout cannot carry a non-cp1252
    # character a lane wrote (gh#574).
    from agentflow._stdio import utf8_stdio

    utf8_stdio()
    a = _build_parser().parse_args(None if argv is None else list(argv))

    # `residue` is a different verdict with different codes, and it owns them. Routing before
    # the refresh try/except rather than inside it is deliberate: this handler maps every
    # ValueError to "the projection was NOT rewritten", which is a sentence about a write that
    # `residue` never attempts. Its own codes are documented on `pillar_residue.run`.
    if a.command == "residue":
        from . import pillar_residue

        try:
            wiki_root = _resolve_wiki_root(a)
        except (FileNotFoundError, ValueError) as exc:
            print(f"pillar residue: CANNOT MEASURE - {exc}", file=sys.stderr)
            return 2
        return pillar_residue.run_cli(a, wiki_root)

    try:
        current, changed = _refresh(_resolve_wiki_root(a), limit=a.limit)
    except (FileNotFoundError, ValueError) as exc:
        # ValueError covers WikiFormatError (a page the refresh could not parse) and the lane and
        # limit guards; all of them mean the projection was NOT rewritten, which is the one thing
        # a calling skill has to be able to tell from the exit code.
        print(f"wiki refresh failed: {exc}", file=sys.stderr)
        return 2
    except OSError as exc:
        # FileNotFoundError is an OSError and is claimed above, on purpose: a missing root is a
        # refusal, not an environment fault. What lands here is everything else the filesystem can
        # say — and it says it to stderr with a code, never as a traceback.
        print(f"wiki refresh failed on the filesystem: {exc!r}", file=sys.stderr)
        return 3
    # SAY WHAT WAS LEFT ALONE, not just what moved. A run that changed nothing is the expected
    # case on most sweeps, and it has to be distinguishable from a run that did not happen --
    # the same reason `issue_intake`'s mirror prints `wrote nothing; unchanged [...]`.
    for path in changed:
        print(path)
    untouched = [p.name for p in current if p not in changed]
    print(
        f"wiki refresh: wrote {len(changed) or 'nothing'}; "
        f"unchanged {untouched or 'nothing'}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
